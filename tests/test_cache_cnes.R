source("src/extract/preparar_cache_cnes.R")
source("src/transform/preparar_estabelecimentos_cnes.R")
local({
  tmp <- tempfile("cache cnes '"); dir.create(tmp)
  on.exit(unlink(tmp, recursive = TRUE))
  fonte <- "tests/fixtures/cnes/202601/tbEstabelecimento202601.csv"
  manifesto <- file.path(tmp, "manifesto.csv")
  m <- data.frame(sha256_csv = sha256_fonte_cnes(fonte), bytes_csv = file.info(fonte)$size)
  write.csv(m, manifesto, row.names = FALSE)
  falha <- function(expr, texto) {
    e <- tryCatch({force(expr); NULL}, error = identity)
    stopifnot(inherits(e, "error"), grepl(texto, conditionMessage(e), fixed = TRUE))
  }
  cache <- preparar_cache_cnes(fonte, manifesto, file.path(tmp, "cache"))
  hash_gz <- sha256_fonte_cnes(cache)
  stopifnot(identical(preparar_cache_cnes(cache, manifesto, dirname(cache)), cache),
            identical(hash_gz, sha256_fonte_cnes(cache)))
  message("OK: importação CSV, reimportação gzip e reutilização idêntica; caminhos com espaços e aspas")
  prefixo <- file.path(tmp, "tbEstabelecimento202601")
  writeLines("version https://git-lfs.github.com/spec/v1", paste0(prefixo, ".csv"))
  falha(ler_csv_cnes(prefixo), "ponteiro Git LFS")
  dados <- ler_csv_cnes(prefixo, arquivo = cache)
  stopifnot(identical(dados$co_cnes, c("0000001", "0000002")))
  est <- preparar_estabelecimentos_cnes("tests/fixtures/cnes", dir_interim = file.path(tmp, "saida"), arquivo_estabelecimentos = cache)
  stopifnot(nrow(est) == 1L, est$co_unidade == "0001", est$cnes == "0000001", est$uf == "ES")
  message("OK: seleção explícita ignora ponteiro; transformação preserva zeros e separa as chaves")
  falha(ler_csv_cnes(prefixo, arquivo = file.path(tmp, "ausente.csv")), "não encontrado")
  m$sha256_csv <- paste(rep("0", 64), collapse = "")
  write.csv(m, manifesto, row.names = FALSE)
  falha(preparar_cache_cnes(fonte, manifesto, file.path(tmp, "divergente")), "Fonte divergente")
  stopifnot(!dir.exists(file.path(tmp, "divergente")))
  m$sha256_csv <- sha256_fonte_cnes(fonte); m$bytes_csv <- m$bytes_csv + 1
  write.csv(m, manifesto, row.names = FALSE)
  falha(preparar_cache_cnes(fonte, manifesto), "Fonte divergente")
  m$bytes_csv <- file.info(fonte)$size; write.csv(m, manifesto, row.names = FALSE)
  writeLines("corrompido", cache)
  corrompido <- sha256_fonte_cnes(cache)
  falha(preparar_cache_cnes(fonte, manifesto, dirname(cache)), "Gzip inválido")
  stopifnot(identical(corrompido, sha256_fonte_cnes(cache)))
  message("OK: fonte ausente, hash/tamanho divergentes e cache corrompido rejeitados sem substituição")
})
